CREATE TABLE IF NOT EXISTS events (
 id TEXT PRIMARY KEY, ts INTEGER NOT NULL, day TEXT NOT NULL,
 visitor TEXT NOT NULL, session TEXT NOT NULL, kind TEXT NOT NULL,
 path TEXT NOT NULL, referrer TEXT NOT NULL DEFAULT '', source TEXT NOT NULL DEFAULT '',
 medium TEXT NOT NULL DEFAULT '', campaign TEXT NOT NULL DEFAULT '', term TEXT NOT NULL DEFAULT '',
 country TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '', device TEXT NOT NULL DEFAULT '',
 browser TEXT NOT NULL DEFAULT '', os TEXT NOT NULL DEFAULT '', seconds INTEGER NOT NULL DEFAULT 0,
 destination TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS events_ts ON events(ts);
CREATE INDEX IF NOT EXISTS events_day ON events(day,kind);
CREATE INDEX IF NOT EXISTS events_session ON events(session,kind);
CREATE TABLE IF NOT EXISTS login_limits (key TEXT PRIMARY KEY, window INTEGER NOT NULL, attempts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS search_imports (id INTEGER PRIMARY KEY, imported_at INTEGER NOT NULL, label TEXT NOT NULL, rows_json TEXT NOT NULL);
